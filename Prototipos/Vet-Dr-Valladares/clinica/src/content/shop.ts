export const findProduct = (id: string) => PRODUCTS.find(p => p.id === id) || KITS.find(p => p.id === id);
export const priceOf = (p: Product, size: string) => (p.sizes.find(s => s.label === size) || p.sizes[0]).price;
// Siempre con el formato de Costa Rica, en los dos idiomas: ₡18 900.
export const money = (n: number) => '₡' + String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
export const kitValue = (kit: Product) => (kit.includes || []).reduce((sum, [id, size]) => sum + priceOf(findProduct(id)!, size), 0);
