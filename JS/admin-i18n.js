const FALLBACK_LANGUAGE = 'en';

/** El diccionario del idioma pedido, con el inglés como respaldo. */
export function adminCopy(language) {
    return ADMIN_COPY[language] || ADMIN_COPY[FALLBACK_LANGUAGE];
}

/**
 * Resuelve `overview.briefingTitle` contra el diccionario. Si la clave no
 * existe en el idioma activo cae al inglés, y si tampoco está ahí devuelve
 * `undefined`: el aplicador deja entonces el texto del HTML tal cual, que es
 * siempre mejor que vaciar el elemento.
 */
export function copyValue(language, path) {
    const walk = source => String(path).split('.').reduce(
        (value, key) => (value == null ? undefined : value[key]), source
    );
    const value = walk(adminCopy(language));
    return value === undefined ? walk(ADMIN_COPY[FALLBACK_LANGUAGE]) : value;
}

// Atributo → propiedad del elemento. El texto va aparte porque no es un
// atributo: `data-i18n` a secas escribe `textContent`.
const ATTRIBUTE_BINDINGS = [
    ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-title', 'title'],
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-alt', 'alt'],
    ['data-i18n-data-placeholder', 'data-placeholder']
];

/**
 * Escribe en el DOM todas las copias declaradas con `data-i18n*`.
 *
 * Se llama en cada cambio de idioma y en cada arranque. Sólo toca elementos
 * marcados: lo que pinta el JS lleva `data-i18n-dynamic` y no se toca aquí,
 * para que un repintado no pise el texto que acaba de escribir su propia vista.
 */
export function applyStaticCopy(language, root = document) {
    root.querySelectorAll('[data-i18n]').forEach(element => {
        const value = copyValue(language, element.dataset.i18n);
        if (typeof value === 'string') element.textContent = value;
    });
    for (const [attribute, property] of ATTRIBUTE_BINDINGS) {
        root.querySelectorAll(`[${attribute}]`).forEach(element => {
            const value = copyValue(language, element.getAttribute(attribute));
            if (typeof value !== 'string') return;
            if (property === 'placeholder' || property === 'title') element[property] = value;
            else element.setAttribute(property, value);
        });
    }
}
